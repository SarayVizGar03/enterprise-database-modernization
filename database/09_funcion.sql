-- 1. Function: Calculate total amount of an order

CREATE OR REPLACE FUNCTION FN_ORDER_TOTAL (
    P_ORDER_ID IN SALES_ORDERS.ORDER_ID%TYPE
)
RETURN NUMBER
AS
    V_TOTAL NUMBER(14,2);
BEGIN
    SELECT NVL(SUM(QUANTITY * UNIT_PRICE), 0)
    INTO V_TOTAL
    FROM ORDER_ITEMS
    WHERE ORDER_ID = P_ORDER_ID;

    RETURN V_TOTAL;
END FN_ORDER_TOTAL;
/


-- 2. Function: Count orders by customer

CREATE OR REPLACE FUNCTION FN_CUSTOMER_ORDER_COUNT (
    P_CUSTOMER_ID IN CUSTOMERS.CUSTOMER_ID%TYPE
)
RETURN NUMBER
AS
    V_TOTAL_ORDERS NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO V_TOTAL_ORDERS
    FROM SALES_ORDERS
    WHERE CUSTOMER_ID = P_CUSTOMER_ID;

    RETURN V_TOTAL_ORDERS;
END FN_CUSTOMER_ORDER_COUNT;
/


-- 3. Function: Get customer email

CREATE OR REPLACE FUNCTION FN_CUSTOMER_EMAIL (
    P_CUSTOMER_ID IN CUSTOMERS.CUSTOMER_ID%TYPE
)
RETURN VARCHAR2
AS
    V_EMAIL CUSTOMERS.EMAIL%TYPE;
BEGIN
    SELECT EMAIL
    INTO V_EMAIL
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = P_CUSTOMER_ID;

    RETURN V_EMAIL;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL;
END FN_CUSTOMER_EMAIL;
/


-- 4. Function: Calculate total sales by branch

CREATE OR REPLACE FUNCTION FN_BRANCH_TOTAL_SALES (
    P_BRANCH_ID IN BRANCHES.BRANCH_ID%TYPE
)
RETURN NUMBER
AS
    V_TOTAL_SALES NUMBER(14,2);
BEGIN
    SELECT NVL(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0)
    INTO V_TOTAL_SALES
    FROM SALES_ORDERS SO
    INNER JOIN ORDER_ITEMS OI
        ON SO.ORDER_ID = OI.ORDER_ID
    WHERE SO.BRANCH_ID = P_BRANCH_ID
      AND SO.STATUS = 'COMPLETED';

    RETURN V_TOTAL_SALES;
END FN_BRANCH_TOTAL_SALES;
/


-- 5. Validate created functions

SELECT
    OBJECT_NAME,
    STATUS
FROM USER_OBJECTS
WHERE OBJECT_TYPE = 'FUNCTION'
AND OBJECT_NAME IN (
    'FN_ORDER_TOTAL',
    'FN_CUSTOMER_ORDER_COUNT',
    'FN_CUSTOMER_EMAIL',
    'FN_BRANCH_TOTAL_SALES'
)
ORDER BY OBJECT_NAME;


-- 6. Review compilation errors

SELECT
    NAME,
    TYPE,
    LINE,
    POSITION,
    TEXT
FROM USER_ERRORS
