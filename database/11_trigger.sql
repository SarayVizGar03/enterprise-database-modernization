-- 1. Create audit table

CREATE TABLE ORDER_STATUS_AUDIT (
    AUDIT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ORDER_ID NUMBER NOT NULL,
    OLD_STATUS VARCHAR2(20),
    NEW_STATUS VARCHAR2(20),
    CHANGE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ORDER_STATUS_AUDIT PRIMARY KEY (AUDIT_ID)
);


-- 2. Trigger: Audit order status changes

CREATE OR REPLACE TRIGGER TRG_AUDIT_ORDER_STATUS
AFTER UPDATE OF STATUS ON SALES_ORDERS
FOR EACH ROW
WHEN (OLD.STATUS <> NEW.STATUS)
BEGIN
    INSERT INTO ORDER_STATUS_AUDIT (
        ORDER_ID,
        OLD_STATUS,
        NEW_STATUS,
        CHANGE_DATE
    )
    VALUES (
        :OLD.ORDER_ID,
        :OLD.STATUS,
        :NEW.STATUS,
        SYSTIMESTAMP
    );
END;
/


-- 3. Trigger: Validate product price

CREATE OR REPLACE TRIGGER TRG_VALIDATE_PRODUCT_PRICE
BEFORE INSERT OR UPDATE OF UNIT_PRICE ON PRODUCTS
FOR EACH ROW
BEGIN
    IF :NEW.UNIT_PRICE <= 0 THEN
        RAISE_APPLICATION_ERROR(
            -20020,
            'Product price must be greater than zero.'
        );
    END IF;
END;
/


-- 4. Trigger: Set default order status

CREATE OR REPLACE TRIGGER TRG_DEFAULT_ORDER_STATUS
BEFORE INSERT ON SALES_ORDERS
FOR EACH ROW
BEGIN
    IF :NEW.STATUS IS NULL THEN
        :NEW.STATUS := 'PENDING';
    END IF;
END;
/


-- 5. Validate created triggers

SELECT
    TRIGGER_NAME,
    TABLE_NAME,
    STATUS,
    TRIGGERING_EVENT
FROM USER_TRIGGERS
WHERE TRIGGER_NAME IN (
    'TRG_AUDIT_ORDER_STATUS',
    'TRG_VALIDATE_PRODUCT_PRICE',
    'TRG_DEFAULT_ORDER_STATUS'
)
ORDER BY TRIGGER_NAME;


-- 6. Review compilation errors

SELECT
    NAME,
    TYPE,
    LINE,
    POSITION,
    TEXT
FROM USER_ERRORS
WHERE TYPE = 'TRIGGER'
AND NAME IN (
    'TRG_AUDIT_ORDER_STATUS',
    'TRG_VALIDATE_PRODUCT_PRICE',
    'TRG_DEFAULT_ORDER_STATUS'
)
ORDER BY NAME, SEQUENCE;


-- 7. Review audit records

SELECT
    AUDIT_ID,
    ORDER_ID,
    OLD_STATUS,
    NEW_STATUS,
    CHANGE_DATE
FROM ORDER_STATUS_AUDIT
ORDER BY AUDIT_ID;
