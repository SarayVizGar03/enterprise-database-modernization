-- 1. Validate total records in each table

SELECT 'BRANCHES' AS TABLE_NAME, COUNT(*) AS TOTAL_RECORDS
FROM BRANCHES

UNION ALL

SELECT 'CUSTOMERS', COUNT(*)
FROM CUSTOMERS

UNION ALL

SELECT 'PRODUCTS', COUNT(*)
FROM PRODUCTS

UNION ALL

SELECT 'SALES_ORDERS', COUNT(*)
FROM SALES_ORDERS

UNION ALL

SELECT 'ORDER_ITEMS', COUNT(*)
FROM ORDER_ITEMS;


-- 2. Validate customer information

SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    FIRST_NAME,
    LAST_NAME,
    EMAIL,
    CREATED_AT
FROM CUSTOMERS
ORDER BY CUSTOMER_ID;


-- 3. Validate products and prices

SELECT
    PRODUCT_ID,
    PRODUCT_NAME,
    CATEGORY,
    UNIT_PRICE
FROM PRODUCTS
ORDER BY PRODUCT_ID;


-- 4. Validate orders with customer and branch information

SELECT
    SO.ORDER_ID,
    C.CUSTOMER_NAME,
    B.BRANCH_NAME,
    SO.ORDER_DATE,
    SO.STATUS
FROM SALES_ORDERS SO
INNER JOIN CUSTOMERS C
    ON SO.CUSTOMER_ID = C.CUSTOMER_ID
INNER JOIN BRANCHES B
    ON SO.BRANCH_ID = B.BRANCH_ID
ORDER BY SO.ORDER_ID;


-- 5. Validate order details

SELECT
    OI.ORDER_ITEM_ID,
    OI.ORDER_ID,
    P.PRODUCT_NAME,
    OI.QUANTITY,
    OI.UNIT_PRICE,
    (OI.QUANTITY * OI.UNIT_PRICE) AS TOTAL_AMOUNT
FROM ORDER_ITEMS OI
INNER JOIN PRODUCTS P
    ON OI.PRODUCT_ID = P.PRODUCT_ID
ORDER BY OI.ORDER_ID;


-- 6. Validate total amount per order

SELECT
    SO.ORDER_ID,
    C.CUSTOMER_NAME,
    SUM(OI.QUANTITY * OI.UNIT_PRICE) AS ORDER_TOTAL
FROM SALES_ORDERS SO
INNER JOIN CUSTOMERS C
    ON SO.CUSTOMER_ID = C.CUSTOMER_ID
INNER JOIN ORDER_ITEMS OI
    ON SO.ORDER_ID = OI.ORDER_ID
GROUP BY
    SO.ORDER_ID,
    C.CUSTOMER_NAME
ORDER BY SO.ORDER_ID;


-- 7. Validate order status distribution

SELECT
    STATUS,
    COUNT(*) AS TOTAL_ORDERS
FROM SALES_ORDERS
GROUP BY STATUS
ORDER BY STATUS;


-- 8. Check for products with invalid prices

SELECT *
FROM PRODUCTS
WHERE UNIT_PRICE <= 0;


-- 9. Check for orders without order items

SELECT
    SO.ORDER_ID,
    SO.STATUS
FROM SALES_ORDERS SO
LEFT JOIN ORDER_ITEMS OI
    ON SO.ORDER_ID = OI.ORDER_ID
WHERE OI.ORDER_ID IS NULL;


-- 10. Check for customers without orders

SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME
FROM CUSTOMERS C
LEFT JOIN SALES_ORDERS SO
    ON C.CUSTOMER_ID = SO.CUSTOMER_ID
WHERE SO.ORDER_ID IS NULL;